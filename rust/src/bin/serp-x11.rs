//! serp-x11 — X11 apps on the glass desktop (niri + xwayland-satellite) at the right size on scaled screens.
//!
//!   serp-x11 sync [--dry-run] [--quiet]   follow the display scale: the Steam scale in niri's environment, old
//!                                         bundled-Qt5 apps wrapped, the DPI of Wine/Lutris prefixes
//!                                         (runs at login and from the installer; changes nothing when up to date)
//!   serp-x11 run [--qt5] -- CMD...        run CMD with the X11 scale variables for the current scale
//!   serp-x11 gamescope [ARGS] -- CMD...   run CMD inside gamescope at the focused screen's native mode
//!                                         (Steam launch options: serp-x11 gamescope -- %command%)
//!   serp-x11 status                       what is in place
//!   serp-x11 undo [--dry-run]             unwrap the desktop entries, drop the overrides, give the Wine DPI back
//!
//! Why: xwayland-satellite shows X11 clients the screen in physical pixels and sets Xft.dpi = 96 x scale (the
//! smallest scale of all screens). GTK, Qt6 and Electron scale from that by themselves. Steam doesn't (it reads
//! STEAM_FORCE_DESKTOPUI_SCALING), Wine doesn't (LogPixels in the prefix) and apps that bundle an old Qt5 don't
//! (only QT_SCALE_FACTOR), so those come out tiny.
//! - Old Qt5 app: the Exec program lives outside /usr, next to a bundled libQt5Core, with no Wayland platform
//!   plugin. A desktop entry of yours is wrapped in place (marked X-Serp-X11=wrapped); a system one gets an
//!   override of the same name in ~/.local/share/applications (marked X-Serp-X11-Source=).
//! - Wine: ~/.wine, $WINEPREFIX, Lutris prefixes and ~/Games/*. Steam's own prefixes (steamapps/compatdata) are
//!   left alone. A DPI you set yourself is kept: only a missing value, 96 or the value serp-x11 wrote is changed
//!   (~/.local/state/serp-x11/state.json). Nothing is written while a wineserver runs.
//! ~/.config/serp-x11/skip lists desktop IDs (file names as in ~/.local/share/applications) that are never wrapped.
//! SERP_X11_SCALE overrides the scale (tests, or no niri running); SERP_X11_BIN the wrapper path in Exec lines.
use glass::{niri, util};
use serde_json::{json, Map, Value};
use std::collections::BTreeSet;
use std::fs;
use std::os::unix::process::CommandExt;
use std::path::{Path, PathBuf};
use std::process::{exit, Command};
use std::time::Duration;

const MARK_WRAPPED: &str = "X-Serp-X11=wrapped";
const KEY_SOURCE: &str = "X-Serp-X11-Source";
const WINE_DEFAULT_DPI: u32 = 96;
const REG_DESKTOP: &str = r"Control Panel\\Desktop";
const REG_FONTS: &str = r"Software\\Wine\\Fonts";
const ENV_HEADER: &str = "// X11 apps (XWayland): settings that follow your display scale.\n\
                          // Generated by serp-x11 (`serp-x11 sync` runs at login); edits here are overwritten.\n";

// ------------------------------------------------------------------ scale

/// Smallest logical scale of the enabled outputs: the one xwayland-satellite bases Xft.dpi on.
fn min_scale(outputs: &Value) -> Option<f64> {
    outputs
        .as_object()?
        .values()
        .filter_map(|o| o.get("logical")?.get("scale")?.as_f64())
        .filter(|s| *s > 0.0)
        .fold(None, |m: Option<f64>, s| Some(m.map_or(s, |m| m.min(s))))
}

fn scale() -> Option<f64> {
    if let Ok(v) = std::env::var("SERP_X11_SCALE") {
        return v.trim().parse::<f64>().ok().filter(|s| *s > 0.0);
    }
    min_scale(&niri::query("Outputs").ok()?)
}

/// 1.5 -> "1.5", 1.25 -> "1.25", 2.0 -> "2", 1.3333 -> "1.33".
fn fmt_scale(s: f64) -> String {
    let t = format!("{:.2}", (s * 100.0).round() / 100.0);
    t.trim_end_matches('0').trim_end_matches('.').to_string()
}

fn dpi_of(s: f64) -> u32 {
    (s * 96.0).round() as u32
}

