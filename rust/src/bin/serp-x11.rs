/// The string unescapes of a desktop-entry value (\s \n \t \r \\).
fn unescape_value(v: &str) -> String {
    let mut out = String::with_capacity(v.len());
    let mut it = v.chars();
    while let Some(c) = it.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match it.next() {
            Some('s') => out.push(' '),
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some('r') => out.push('\r'),
            Some('\\') => out.push('\\'),
            Some(o) => {
                out.push('\\');
                out.push(o);
            }
            None => out.push('\\'),
        }
    }
    out
}

/// Split an Exec value into its arguments (desktop-entry quoting rules).
fn exec_args(v: &str) -> Vec<String> {
    let v = unescape_value(v);
    let (mut args, mut cur, mut quoted, mut any) = (Vec::new(), String::new(), false, false);
    let mut it = v.chars();
    while let Some(c) = it.next() {
        if quoted {
            match c {
                '"' => quoted = false,
                '\\' => cur.extend(it.next()),
                _ => cur.push(c),
            }
            continue;
        }
        match c {
            '"' => {
                quoted = true;
                any = true;
            }
            ' ' | '\t' | '\n' => {
                if any || !cur.is_empty() {
                    args.push(std::mem::take(&mut cur));
                    any = false;
                }
            }
            _ => cur.push(c),
        }
    }
    if any || !cur.is_empty() {
        args.push(cur);
    }
    args
}

fn is_assignment(a: &str) -> bool {
    match a.find('=') {
        Some(p) if p > 0 => {
            let name = &a[..p];
            !name.starts_with(|c: char| c.is_ascii_digit()) && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        }
        _ => false,
    }
}

/// The program an Exec line runs: past `env`, its options and VAR=value words.
fn exec_program(args: &[String]) -> Option<&str> {
    let mut i = 0;
    if args.first().map_or(false, |a| a == "env" || a.ends_with("/env")) {
        i = 1;
        while i < args.len() && args[i].starts_with('-') {
            i += if args[i] == "-u" || args[i] == "--unset" { 2 } else { 1 };
        }
    }
    while i < args.len() && is_assignment(&args[i]) {
        i += 1;
    }
    args.get(i).map(String::as_str).filter(|s| !s.starts_with('%'))
}

/// An Exec argument as the spec wants it written: double-quoted when it has reserved characters.
fn quote_exec_arg(a: &str) -> String {
    let reserved = |c: char| " \t\n\"'\\><~|&;$*?#()`".contains(c);
    let body = if a.contains(reserved) {
        let mut q = String::from("\"");
        for c in a.chars() {
            if matches!(c, '"' | '`' | '$' | '\\') {
                q.push('\\');
            }
            q.push(c);
        }
        q.push('"');
        q
    } else {
        a.to_string()
    };
    body.replace('\\', "\\\\") // the value-level escape on top of the quoting
}

fn is_wrapped_exec(v: &str) -> bool {
    let a = exec_args(v);
    a.len() >= 2 && Path::new(&a[0]).file_name().map_or(false, |n| n == "serp-x11") && a[1] == "run"
}

fn wrap_exec(v: &str, bin: &str) -> String {
    format!("{} run --qt5 -- {}", quote_exec_arg(bin), v)
}

fn unwrap_exec(v: &str) -> String {
    if !is_wrapped_exec(v) {
        return v.to_string();
    }
    match v.find(" -- ") {
        Some(p) => v[p + 4..].trim_start().to_string(),
        None => v.to_string(),
    }
}

/// `key` in the [Desktop Entry] group.
fn entry_get(text: &str, key: &str) -> Option<String> {
    let mut in_main = false;
    for line in text.lines() {
        let t = line.trim();
        if t.starts_with('[') {
            in_main = t == "[Desktop Entry]";
            continue;
        }
        if !in_main || t.starts_with('#') {
            continue;
        }
        if let Some((k, v)) = t.split_once('=') {
            if k.trim() == key {
                return Some(v.trim().to_string());
            }
        }
    }
    None
}

/// Apply `f` to every Exec= value of the entry and its actions; `mark` (a key=value line, or nothing) goes
/// right under [Desktop Entry], and lines starting with any of `drop` are removed.
fn rewrite_entry(text: &str, f: impl Fn(&str) -> String, mark: Option<&str>, drop: &[&str]) -> String {
    let mut out = String::with_capacity(text.len() + 128);
    let mut in_group = false;
    for line in text.lines() {
        let t = line.trim();
        if t.starts_with('[') {
            in_group = t == "[Desktop Entry]" || t.starts_with("[Desktop Action ");
            out.push_str(line);
            out.push('\n');
            if t == "[Desktop Entry]" {
                if let Some(m) = mark {
                    out.push_str(m);
                    out.push('\n');
                }
            }
            continue;
        }
        if drop.iter().any(|d| t.starts_with(d)) {
            continue;
        }
        if in_group {
            if let Some((k, v)) = line.split_once('=') {
                if k.trim() == "Exec" {
                    out.push_str("Exec=");
                    out.push_str(&f(v.trim()));
                    out.push('\n');
                    continue;
                }
            }
        }
        out.push_str(line);
        out.push('\n');
    }
    out
}

fn wrap_in_place(text: &str, bin: &str) -> String {
    rewrite_entry(text, |v| if is_wrapped_exec(v) { v.to_string() } else { wrap_exec(v, bin) }, Some(MARK_WRAPPED), &[MARK_WRAPPED])
}

fn unwrap_in_place(text: &str) -> String {
    rewrite_entry(text, unwrap_exec, None, &[MARK_WRAPPED])
}

fn override_text(src_text: &str, src: &Path, bin: &str) -> String {
    let mark = format!("{KEY_SOURCE}={}", src.display());
    let body = rewrite_entry(src_text, |v| if is_wrapped_exec(v) { v.to_string() } else { wrap_exec(v, bin) }, Some(&mark), &[KEY_SOURCE]);
    format!("# Generated by serp-x11 from {} (an app with its own old Qt5, scaled for XWayland).\n# `serp-x11 undo` removes it.\n{body}", src.display())
}

/// Every *.desktop under `dir` with its desktop ID (subfolders joined with '-').
fn desktop_files(dir: &Path) -> Vec<(String, PathBuf)> {
    fn walk(base: &Path, dir: &Path, depth: u32, out: &mut Vec<(String, PathBuf)>) {
        let Ok(rd) = fs::read_dir(dir) else { return };
        for e in rd.flatten() {
            let p = e.path();
            let Ok(ft) = e.file_type() else { continue };
            if ft.is_dir() && depth < 4 {
                walk(base, &p, depth + 1, out);
            } else if (ft.is_file() || ft.is_symlink()) && p.extension().map_or(false, |x| x == "desktop") {
                if let Ok(rel) = p.strip_prefix(base) {
                    out.push((rel.to_string_lossy().replace('/', "-"), p.clone()));
                }
            }
        }
    }
    let mut out = Vec::new();
    walk(dir, dir, 0, &mut out);
    out.sort();
    out
}

fn has_file_prefix(dir: &Path, prefix: &str) -> bool {
    fs::read_dir(dir).map_or(false, |rd| rd.flatten().any(|e| e.file_name().to_str().map_or(false, |n| n.starts_with(prefix))))
}

/// A `platforms/libqwayland*` plugin within `depth` folder levels of `root` (symlinked folders not followed).
fn has_wayland_plugin(root: &Path, depth: u32, budget: &mut u32) -> bool {
    let Ok(rd) = fs::read_dir(root) else { return false };
    for e in rd.flatten() {
        if *budget == 0 {
            return false;
        }
        *budget -= 1;
        if !e.file_type().map_or(false, |t| t.is_dir()) {
            continue;
        }
        let p = e.path();
        if e.file_name() == "platforms" && has_file_prefix(&p, "libqwayland") {
            return true;
        }
        if depth > 0 && has_wayland_plugin(&p, depth - 1, budget) {
            return true;
        }
    }
    false
}

fn is_system_path(p: &Path) -> bool {
    ["/usr/", "/bin/", "/sbin/", "/lib/", "/lib64/", "/etc/"].iter().any(|s| p.starts_with(s))
}

/// The folder with the bundled libQt5Core when `prog` is an X11-only app with its own Qt5.
fn bundled_qt5(prog: &Path) -> Option<PathBuf> {
    if is_system_path(prog) {
        return None;
    }
    let dir = prog.parent()?;
    let mut cands = vec![dir.to_path_buf(), dir.join("bin"), dir.join("lib"), dir.join("lib64")];
    if let Some(up) = dir.parent() {
        cands.push(up.join("lib"));
    }
    let qt = cands.into_iter().find(|d| has_file_prefix(d, "libQt5Core.so"))?;
    let mut budget = 20_000;
    if has_wayland_plugin(dir, 3, &mut budget) || (!qt.starts_with(dir) && has_wayland_plugin(&qt, 3, &mut budget)) {
        return None;
    }
    Some(qt)
}

/// The bundled-Qt5 folder of the program a desktop entry starts (None for anything else).
fn entry_qt5(text: &str) -> Option<PathBuf> {
    if entry_get(text, "Type").map_or(false, |t| t != "Application") || entry_get(text, "Hidden").as_deref() == Some("true") {
        return None;
    }
    let exec = unwrap_exec(&entry_get(text, "Exec")?);
    let args = exec_args(&exec);
    let prog = which(exec_program(&args)?)?;
    bundled_qt5(&fs::canonicalize(prog).ok()?)
}

fn skip_ids() -> BTreeSet<String> {
    fs::read_to_string(config_home().join("serp-x11/skip"))
        .map(|s| s.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')).map(String::from).collect())
        .unwrap_or_default()
}

fn write_like(path: &Path, text: &str) -> std::io::Result<()> {
    let perm = fs::metadata(path).map(|m| m.permissions()).ok();
    util::write_atomic(path, text.as_bytes())?;
    if let Some(p) = perm {
        fs::set_permissions(path, p)?;
    }
    Ok(())
}

fn sync_desktop(cx: &mut Ctx) {
    let user_dir = data_home().join("applications");
    let bin = wrapper_bin();
    let skip = skip_ids();
    let before = cx.changes;
    let mut seen: BTreeSet<String> = BTreeSet::new();

    for (id, path) in desktop_files(&user_dir) {
        seen.insert(id.clone());
        let Ok(text) = fs::read_to_string(&path) else { continue };
        if let Some(src) = entry_get(&text, KEY_SOURCE) {
            let src = PathBuf::from(src);
            let want = fs::read_to_string(&src)
                .ok()
                .filter(|st| !skip.contains(&id) && entry_qt5(st).is_some())
                .map(|st| override_text(&st, &src, &bin));
            match want {
                Some(w) if w == text => {}
                Some(w) => {
                    cx.change(format!("update the scaled copy of {id}"), || util::write_atomic(&path, w.as_bytes()));
                }
                None => {
                    cx.change(format!("remove the scaled copy of {id} (its app changed or is gone)"), || fs::remove_file(&path));
                }
            }
            continue;
        }
        let wrapped = text.lines().any(|l| l.trim() == MARK_WRAPPED);
        let qt = if skip.contains(&id) { None } else { entry_qt5(&text) };
        match (wrapped, qt) {
            (true, Some(_)) => {
                let w = wrap_in_place(&text, &bin);
                if w != text {
                    cx.change(format!("re-wrap {id}"), || write_like(&path, &w));
                }
            }
            (true, None) => {
                let w = unwrap_in_place(&text);
                cx.change(format!("unwrap {id} (no longer an old-Qt5 app, or skipped)"), || write_like(&path, &w));
            }
            (false, Some(q)) => {
                let w = wrap_in_place(&text, &bin);
                let backup = state_dir().join("backup").join(&id);
                cx.change(format!("wrap {id} so it's scaled (its own Qt5 in {})", tilde(&q)), || {
                    if !backup.exists() {
                        fs::create_dir_all(backup.parent().unwrap())?;
                        fs::write(&backup, &text)?;
                    }
                    write_like(&path, &w)
                });
            }
            (false, None) => {}
        }
    }

    for dir in data_dirs() {
        let apps = dir.join("applications");
        if apps == user_dir {
            continue;
        }
        for (id, path) in desktop_files(&apps) {
            if !seen.insert(id.clone()) || skip.contains(&id) {
                continue; // a user entry (or an earlier data dir) wins
            }
            let Ok(text) = fs::read_to_string(&path) else { continue };
            let Some(q) = entry_qt5(&text) else { continue };
            let dst = user_dir.join(path.strip_prefix(&apps).unwrap_or(Path::new(&id)));
            let src = fs::canonicalize(&path).unwrap_or(path.clone());
            let w = override_text(&text, &src, &bin);
            cx.change(format!("add a scaled copy of {id} (its own Qt5 in {})", tilde(&q)), || {
                fs::create_dir_all(dst.parent().unwrap())?;
                util::write_atomic(&dst, w.as_bytes())
            });
        }
    }

    if cx.changes > before && !cx.dry && which("update-desktop-database").is_some() {
        util::run_quiet(&["update-desktop-database", &user_dir.to_string_lossy()], Duration::from_secs(20));
    }
}

fn undo_desktop(cx: &mut Ctx) {
    let user_dir = data_home().join("applications");
    for (id, path) in desktop_files(&user_dir) {
        let Ok(text) = fs::read_to_string(&path) else { continue };
        if entry_get(&text, KEY_SOURCE).is_some() {
            cx.change(format!("remove the scaled copy of {id}"), || fs::remove_file(&path));
        } else if text.lines().any(|l| l.trim() == MARK_WRAPPED) {
            let w = unwrap_in_place(&text);
            cx.change(format!("unwrap {id}"), || write_like(&path, &w));
        }
    }
}

// ------------------------------------------------------------------ Wine DPI

fn section_bounds(lines: &[&str], name: &str) -> Option<(usize, usize)> {
    let head = format!("[{name}]");
    let start = lines.iter().position(|l| l.starts_with(&head))?;
    let end = lines[start + 1..].iter().position(|l| l.starts_with('[')).map_or(lines.len(), |p| start + 1 + p);
    Some((start, end))
}

fn parse_dword(line: &str) -> Option<u32> {
    let v = line.strip_prefix("\"LogPixels\"=dword:")?;
    u32::from_str_radix(v.trim(), 16).ok()
}

/// LogPixels in a user.reg section.
fn reg_logpixels(text: &str, section: &str) -> Option<u32> {
    let lines: Vec<&str> = text.lines().collect();
    let (s, e) = section_bounds(&lines, section)?;
    lines[s + 1..e].iter().find_map(|l| parse_dword(l))
}

/// user.reg with LogPixels = `dpi`: set (or added) under Control Panel\Desktop, and set under Wine\Fonts where
/// that already has one.
fn set_logpixels(text: &str, dpi: u32, now: u64) -> String {
    let value = format!("\"LogPixels\"=dword:{dpi:08x}");
    let mut lines: Vec<String> = text.lines().map(String::from).collect();
    for section in [REG_FONTS, REG_DESKTOP] {
        let refs: Vec<&str> = lines.iter().map(String::as_str).collect();
        match section_bounds(&refs, section) {
            Some((s, e)) => {
                if let Some(i) = (s + 1..e).find(|&i| parse_dword(&lines[i]).is_some()) {
                    lines[i] = value.clone();
                } else if section == REG_DESKTOP {
                    let mut at = s + 1;
                    while at < e && lines[at].starts_with('#') {
                        at += 1;
                    }
                    lines.insert(at, value.clone());
                }
            }
            None if section == REG_DESKTOP => {
                if lines.last().map_or(false, |l| !l.is_empty()) {
                    lines.push(String::new());
                }
                lines.push(format!("[{REG_DESKTOP}] {now}"));
                lines.push(value.clone());
            }
            None => {}
        }
    }
    let mut out = lines.join("\n");
    out.push('\n');
    out
}

#[derive(Debug, PartialEq)]
enum WineAct {
    Same,
    Set,
    Yours(u32),
}

fn wine_decide(cur: Option<u32>, want: u32, ours: Option<u32>) -> WineAct {
    match cur {
        Some(c) if c == want => WineAct::Same,
        None => WineAct::Set,
        Some(c) if c == WINE_DEFAULT_DPI || Some(c) == ours => WineAct::Set,
        Some(c) => WineAct::Yours(c),
    }
}

/// `prefix:` paths in a Lutris game config (only literal ones, not $GAMEDIR and the like).
fn lutris_prefixes(yml: &str) -> Vec<PathBuf> {
    yml.lines()
        .filter_map(|l| l.trim().strip_prefix("prefix:"))
        .map(|v| v.trim().trim_matches(|c| c == '"' || c == '\''))
        .filter(|v| !v.is_empty() && !v.contains('$'))
        .filter_map(|v| match v.strip_prefix("~/") {
            Some(rest) => Some(util::home().join(rest)),
            None => v.starts_with('/').then(|| PathBuf::from(v)),
        })
        .collect()
}

/// user.reg of every Wine prefix serp-x11 looks after (canonical, no duplicates, no Steam prefixes).
fn wine_regs() -> Vec<PathBuf> {
    let home = util::home();
    let mut prefixes = vec![home.join(".wine")];
    if let Some(p) = std::env::var_os("WINEPREFIX").filter(|p| !p.is_empty()) {
        prefixes.push(PathBuf::from(p));
    }
    for dir in [data_home().join("lutris/games"), config_home().join("lutris/games")] {
        for e in fs::read_dir(dir).into_iter().flatten().flatten() {
            if e.path().extension().map_or(false, |x| x == "yml") {
                prefixes.extend(lutris_prefixes(&fs::read_to_string(e.path()).unwrap_or_default()));
            }
        }
    }
    for e in fs::read_dir(home.join("Games")).into_iter().flatten().flatten() {
        prefixes.push(e.path());
    }
    let mut out = BTreeSet::new();
    for p in prefixes {
        for reg in [p.join("user.reg"), p.join("pfx/user.reg")] {
            if let Ok(c) = fs::canonicalize(&reg) {
                if c.is_file() && !c.to_string_lossy().contains("/steamapps/compatdata/") {
                    out.insert(c);
                    break;
                }
            }
        }
    }
    out.into_iter().collect()
}

fn prefix_of(reg: &Path) -> &Path {
    reg.parent().unwrap_or(reg)
}

fn load_state() -> Value {
    fs::read_to_string(state_dir().join("state.json")).ok().and_then(|s| serde_json::from_str(&s).ok()).unwrap_or_else(|| json!({}))
}

fn save_state(st: &Value) -> std::io::Result<()> {
    fs::create_dir_all(state_dir())?;
    util::write_atomic(state_dir().join("state.json"), format!("{}\n", serde_json::to_string_pretty(st).unwrap()).as_bytes())
}

fn wine_state(st: &mut Value) -> &mut Map<String, Value> {
    if !st.get("wine").map_or(false, Value::is_object) {
        st["wine"] = json!({});
    }
    st["wine"].as_object_mut().unwrap()
}

fn sync_wine(cx: &mut Ctx, scale: Option<f64>) {
    let Some(s) = scale else { return };
    let regs = wine_regs();
    if regs.is_empty() {
        return;
    }
    if proc_running("wineserver") {
        cx.note("Wine is running, so the Wine DPI is checked at the next login");
        return;
    }
    let want = dpi_of(s);
    let mut st = load_state();
    let mut dirty = false;
    for reg in regs {
        let key = reg.to_string_lossy().into_owned();
        let Ok(text) = fs::read_to_string(&reg) else { continue };
        let cur = reg_logpixels(&text, REG_DESKTOP);
        let ours = wine_state(&mut st).get(&key).and_then(|v| v.get("wrote")).and_then(Value::as_u64).map(|v| v as u32);
        match wine_decide(cur, want, ours) {
            WineAct::Same => {}
            WineAct::Yours(v) => {
                if !cx.quiet {
                    println!("serp-x11: kept your Wine DPI {v} in {}", tilde(prefix_of(&reg)));
                }
            }
            WineAct::Set => {
                let now = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map_or(0, |d| d.as_secs());
                let new = set_logpixels(&text, want, now);
                let bak = reg.with_file_name("user.reg.serp-x11.bak");
                let was = cur.map_or(" (was unset)".to_string(), |c| format!(" (was {c})"));
                if cx.change(format!("set the Wine DPI to {want} in {}{was}", tilde(prefix_of(&reg))), || {
                    if !bak.exists() {
                        fs::copy(&reg, &bak)?;
                    }
                    util::write_atomic(&reg, new.as_bytes())
                }) && !cx.dry
                {
                    let w = wine_state(&mut st);
                    let orig = match w.get(&key) {
                        Some(e) => e.get("was").cloned().unwrap_or(Value::Null),
                        None => cur.map_or(Value::Null, |c| json!(c)),
                    };
                    w.insert(key, json!({ "wrote": want, "was": orig }));
                    dirty = true;
                }
            }
        }
    }
    if dirty {
        if let Err(e) = save_state(&st) {
            eprintln!("serp-x11: can't save {}: {e}", tilde(&state_dir().join("state.json")));
        }
    }
}

fn undo_wine(cx: &mut Ctx) {
    let mut st = load_state();
    let entries: Vec<(String, Value)> = wine_state(&mut st).iter().map(|(k, v)| (k.clone(), v.clone())).collect();
    if entries.is_empty() {
        return;
    }
    if proc_running("wineserver") {
        cx.errors += 1;
        eprintln!("serp-x11: Wine is running: close it first, then run `serp-x11 undo` again for the Wine DPI");
        return;
    }
    for (key, e) in entries {
        let reg = PathBuf::from(&key);
        let wrote = e.get("wrote").and_then(Value::as_u64).map(|v| v as u32);
        let was = e.get("was").and_then(Value::as_u64).map_or(WINE_DEFAULT_DPI, |v| v as u32);
        let text = fs::read_to_string(&reg).unwrap_or_default();
        if !text.is_empty() && reg_logpixels(&text, REG_DESKTOP) == wrote {
            let new = set_logpixels(&text, was, 0);
            if !cx.change(format!("give {} its Wine DPI {was} back", tilde(prefix_of(&reg))), || util::write_atomic(&reg, new.as_bytes())) {
                continue;
            }
        }
        if !cx.dry {
            wine_state(&mut st).remove(&key);
        }
    }
    if !cx.dry {
        let _ = save_state(&st);
    }
}

// ------------------------------------------------------------------ commands

fn cmd_sync(args: &[String]) {
    let mut cx = Ctx { dry: args.iter().any(|a| a == "--dry-run"), quiet: args.iter().any(|a| a == "--quiet"), changes: 0, errors: 0 };
    let lock_path = util::runtime_dir().join("serp-x11.lock");
    let _lock = match util::try_lock(&lock_path) {
        Ok(Some(l)) => Some(l),
        Ok(None) => {
            cx.note("another serp-x11 sync is running");
            return;
        }
        Err(_) => None,
    };
    let s = scale();
    sync_env(&mut cx, s);
    sync_desktop(&mut cx);
    sync_wine(&mut cx, s);
    if cx.changes == 0 {
        cx.note(&match s {
            Some(s) => format!("X11 apps are set up for scale {} (nothing to change)", fmt_scale(s)),
            None => "nothing to change".into(),
        });
    }
    if cx.errors > 0 {
        exit(1);
    }
}

fn cmd_undo(args: &[String]) {
    let mut cx = Ctx { dry: args.iter().any(|a| a == "--dry-run"), quiet: false, changes: 0, errors: 0 };
    undo_desktop(&mut cx);
    undo_wine(&mut cx);
    reset_env(&mut cx);
    let user_dir = data_home().join("applications");
    if cx.changes > 0 && !cx.dry && which("update-desktop-database").is_some() {
        util::run_quiet(&["update-desktop-database", &user_dir.to_string_lossy()], Duration::from_secs(20));
    }
    if cx.changes == 0 {
        cx.note("nothing to undo");
    }
    if cx.errors > 0 {
        exit(1);
    }
}

fn exec_or_die(c: &mut Command, what: &str) -> ! {
    let e = c.exec();
    eprintln!("serp-x11: can't run {what}: {e}");
    exit(127)
}

fn split_dashdash(args: &[String]) -> (&[String], &[String]) {
    match args.iter().position(|a| a == "--") {
        Some(p) => (&args[..p], &args[p + 1..]),
        None => (&[], args),
    }
}

fn cmd_run(args: &[String]) -> ! {
    let (opts, cmd) = split_dashdash(args);
    let (opts, cmd) = if opts.is_empty() && cmd.first().map_or(false, |a| a == "--qt5") { (&cmd[..1], &cmd[1..]) } else { (opts, cmd) };
    let qt5 = opts.iter().any(|a| a == "--qt5");
    let Some(prog) = cmd.first() else { usage() };
    let mut c = Command::new(prog);
    c.args(&cmd[1..]);
    if let Some(s) = scale() {
        let f = fmt_scale(s);
        c.env("STEAM_FORCE_DESKTOPUI_SCALING", &f);
        if qt5 && std::env::var_os("QT_SCALE_FACTOR").is_none() {
            c.env("QT_SCALE_FACTOR", &f);
        }
    }
    if qt5 {
        c.env("QT_QPA_PLATFORM", "xcb"); // its bundled Qt has no Wayland plugin
    }
    exec_or_die(&mut c, prog)
}

/// gamescope's arguments: the user's, plus fullscreen at the focused screen's native mode where they gave none.
fn gamescope_args(user: &[String], mode: Option<(u64, u64, u64)>) -> Vec<String> {
    let has = |flags: &[&str]| user.iter().any(|a| flags.contains(&a.as_str()));
    let mut a: Vec<String> = user.to_vec();
    let mut add = |flags: &[&str], vals: &[String]| {
        if !has(flags) {
            a.push(flags[0].to_string());
            a.extend(vals.iter().cloned());
        }
    };
    if let Some((w, h, hz)) = mode {
        add(&["-W", "--output-width"], &[w.to_string()]);
        add(&["-H", "--output-height"], &[h.to_string()]);
        add(&["-w", "--nested-width"], &[w.to_string()]);
        add(&["-h", "--nested-height"], &[h.to_string()]);
        add(&["-r", "--nested-refresh"], &[hz.to_string()]);
    }
    add(&["-f", "--fullscreen"], &[]);
    add(&["--force-grab-cursor"], &[]);
    add(&["--backend"], &["sdl".to_string()]);
    a
}

fn focused_mode() -> Option<(u64, u64, u64)> {
    let o = niri::query("FocusedOutput").ok()?;
    let m = o.get("modes")?.get(o.get("current_mode")?.as_u64()? as usize)?;
    let hz = (m.get("refresh_rate")?.as_u64()? as f64 / 1000.0).round() as u64;
    Some((m.get("width")?.as_u64()?, m.get("height")?.as_u64()?, hz))
}

fn cmd_gamescope(args: &[String]) -> ! {
    let (user, cmd) = split_dashdash(args);
    let Some(prog) = cmd.first() else { usage() };
    if which("gamescope").is_none() {
        eprintln!("serp-x11: gamescope isn't installed, starting the game without it");
        exec_or_die(Command::new(prog).args(&cmd[1..]), prog);
    }
    let mut c = Command::new("gamescope");
    c.args(gamescope_args(user, focused_mode())).arg("--").args(cmd);
    exec_or_die(&mut c, "gamescope")
}

fn cmd_status() {
    let s = scale();
    let row = |k: &str, v: String| println!("{k:<20}{v}");
    row(
        "xwayland-satellite",
        match which("xwayland-satellite") {
            Some(p) if proc_running("xwayland-satell") => format!("{} (running)", p.display()),
            Some(p) => format!("{} (niri starts it when an X11 app opens)", p.display()),
            None => "NOT INSTALLED: X11 apps can't open (pacman -S xwayland-satellite)".into(),
        },
    );
    let display = std::env::var("DISPLAY").unwrap_or_default();
    let mut xdpi = String::new();
    if !display.is_empty() && proc_running("xwayland-satell") && which("xprop").is_some() {
        if let Some(out) = util::run_output(&["xprop", "-root", "RESOURCE_MANAGER"], Duration::from_secs(3)) {
            if let Some(p) = out.find("Xft.dpi:") {
                let v: String = out[p + 8..].trim_start_matches(|c: char| c == '\\' || c == 't' || c.is_whitespace()).chars().take_while(|c| c.is_ascii_digit()).collect();
                xdpi = format!(" (Xft.dpi {v})");
            }
        }
    }
    row("X display", if display.is_empty() { "not set in this shell".into() } else { format!("{display}{xdpi}") });
    row(
        "scale",
        match s {
            Some(s) => format!("{} -> Steam {0}, Wine DPI {}, old Qt5 apps QT_SCALE_FACTOR {0}", fmt_scale(s), dpi_of(s)),
            None => "unknown (niri isn't reachable)".into(),
        },
    );
    let envf = niri_env_file();
    row(
        "niri env",
        match fs::read_to_string(&envf) {
            Ok(t) if Some(t.as_str()) == s.map(|s| niri_env_text(Some(s))).as_deref() => format!("{} up to date", tilde(&envf)),
            Ok(_) => format!("{} out of date: run serp-x11 sync", tilde(&envf)),
            Err(_) => format!("{} missing", tilde(&envf)),
        },
    );
    let mut apps = Vec::new();
    for (id, path) in desktop_files(&data_home().join("applications")) {
        let text = fs::read_to_string(&path).unwrap_or_default();
        if let Some(src) = entry_get(&text, KEY_SOURCE) {
            apps.push(format!("{id} (scaled copy of {src})"));
        } else if text.lines().any(|l| l.trim() == MARK_WRAPPED) {
            apps.push(format!("{id} (wrapped)"));
        }
    }
    row("old Qt5 apps", if apps.is_empty() { "none found".into() } else { apps.join(", ") });
    let mut st = load_state();
    let ours = wine_state(&mut st).clone();
    let regs = wine_regs();
    if regs.is_empty() {
        row("Wine prefixes", "none found".into());
    }
    for (i, reg) in regs.iter().enumerate() {
        let text = fs::read_to_string(reg).unwrap_or_default();
        let cur = reg_logpixels(&text, REG_DESKTOP);
        let who = match ours.get(reg.to_string_lossy().as_ref()) {
            Some(e) if e.get("wrote").and_then(Value::as_u64) == cur.map(u64::from) => {
                format!(", set by serp-x11, was {}", e.get("was").and_then(Value::as_u64).map_or("unset".into(), |v| v.to_string()))
            }
            _ => String::new(),
        };
        let v = cur.map_or("DPI unset (96)".into(), |c| format!("DPI {c}"));
        row(if i == 0 { "Wine prefixes" } else { "" }, format!("{}: {v}{who}", tilde(prefix_of(reg))));
    }
    row(
        "gamescope",
        match which("gamescope") {
            Some(p) => format!("{} (game launch options: serp-x11 gamescope -- %command%)", p.display()),
            None => "not installed".into(),
        },
    );
}

fn usage() -> ! {
    eprintln!(
        "usage: serp-x11 sync [--dry-run] [--quiet] | run [--qt5] -- CMD... | gamescope [ARGS] -- CMD... | status | undo [--dry-run]"
    );
    exit(2)
}

fn main() {
    util::ignore_sigpipe();
    let args: Vec<String> = std::env::args().skip(1).collect();
    let rest = args.get(1..).unwrap_or(&[]);
    match args.first().map(String::as_str) {
        Some("sync") => cmd_sync(rest),
        Some("run") => cmd_run(rest),
        Some("gamescope") => cmd_gamescope(rest),
        Some("status") | None => cmd_status(),
        Some("undo") => cmd_undo(rest),
        _ => usage(),
    }
}

