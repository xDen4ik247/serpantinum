"""Writes src/pytables.rs: CPython's own str tables (casefold, lower, isspace, the re module's \\w),
so the Rust backend matches the Python one exactly. Run with the Python the app used to run on."""
import re
import sys

W = re.compile(r"\w")


def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        ok = pred(c)
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def lit(s):
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in s) + '"'


def maps(fn):
    out = []
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        ch = chr(c)
        m = fn(ch)
        if m != ch:
            out.append(f"({c:#x}, {lit(m)})")
    return out


o = [f"//! Generated by tools/gen_pystr.py from Python {sys.version.split()[0]}: do not edit.\n"]
o.append("pub static WORD: &[(u32, u32)] = &[" + ", ".join(f"({a:#x}, {b:#x})" for a, b in
         ranges(lambda c: not 0xD800 <= c <= 0xDFFF and bool(W.match(chr(c))))) + "];\n")
o.append("pub static SPACE: &[(u32, u32)] = &[" + ", ".join(f"({a:#x}, {b:#x})" for a, b in
         ranges(lambda c: chr(c).isspace())) + "];\n")
o.append("pub static DECIMAL: &[(u32, u32)] = &[" + ", ".join(f"({a:#x}, {b:#x})" for a, b in
         ranges(lambda c: chr(c).isdecimal())) + "];\n")
o.append("pub static CASEFOLD: &[(u32, &str)] = &[" + ", ".join(maps(str.casefold)) + "];\n")
o.append("pub static LOWER: &[(u32, &str)] = &[" + ", ".join(maps(str.lower)) + "];\n")
open("src/pytables.rs", "w").write("\n".join(o))
