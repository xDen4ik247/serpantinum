#!/usr/bin/env python3
"""Generate src/mimetab.rs from Python's mimetypes (as initialised on this system, /etc/mime.types
included): guess_extension(type) and guess_type(name). Run from backend/."""
import mimetypes

mimetypes.init()
types = sorted(set(mimetypes.types_map.values()) | set(mimetypes.common_types.values()))
ext_of = []
for t in types:
    e = mimetypes.guess_extension(t)
    if e:
        ext_of.append((t, e))
type_of = sorted((e, t) for e, t in mimetypes.types_map.items())
q = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
lines = ["//! Generated by tools/gen_mimetypes.py from Python's mimetypes. Do not edit.", "",
         "/// mimetypes.guess_extension(type)", "pub static EXT_OF: &[(&str, &str)] = &["]
lines += [f"    ({q(t)}, {q(e)})," for t, e in ext_of]
lines += ["];", "", "/// mimetypes.types_map (extension -> type), sorted", "pub static TYPE_OF: &[(&str, &str)] = &["]
lines += [f"    ({q(e)}, {q(t)})," for e, t in type_of]
lines += ["];", ""]
open("src/mimetab.rs", "w").write("\n".join(lines))
print(len(ext_of), "types,", len(type_of), "extensions")
