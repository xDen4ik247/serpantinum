#!/usr/bin/env python3
"""Generate src/entities.rs from CPython's html / html.entities: the HTML5 named character
references and html.unescape's tables for invalid numeric references.  Run from backend/."""
import html, html.entities


def rs(s):
    o = '"'
    for ch in s:
        c = ord(ch)
        if ch == '"':
            o += '\\"'
        elif ch == '\\':
            o += '\\\\'
        elif c < 0x20 or c == 0x7f or 0x80 <= c <= 0x9f or ch in '  ':
            o += '\\u{%x}' % c
        else:
            o += ch
    return o + '"'


lines = ["//! Generated by tools/gen_entities.py from CPython's html / html.entities. Do not edit.",
         "", "/// (name, replacement) of html.entities.html5, sorted by name (binary search).",
         "pub static HTML5: &[(&str, &str)] = &["]
for k in sorted(html.entities.html5):
    lines.append(f"    ({rs(k)}, {rs(html.entities.html5[k])}),")
lines += ["];", "", "/// html._invalid_charrefs", "pub static INVALID_CHARREFS: &[(u32, &str)] = &["]
for k in sorted(html._invalid_charrefs):
    lines.append(f"    ({k:#x}, {rs(html._invalid_charrefs[k])}),")
lines += ["];", "", "/// html._invalid_codepoints", "pub static INVALID_CODEPOINTS: &[u32] = &["]
for k in sorted(html._invalid_codepoints):
    lines.append(f"    {k:#x},")
lines += ["];", ""]
open("src/entities.rs", "w", encoding="utf-8").write("\n".join(lines))
